const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const postcss = require('postcss');
const tailwind = require('@tailwindcss/postcss');
const webpackModule = require('next/dist/compiled/webpack/webpack');
const webpack = webpackModule.webpack || webpackModule.default;
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');

(async () => {
  const root = path.resolve(__dirname, '..');
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'personal-notes-qa-'));
  const output = path.join(directory, 'notes.js');
  const alias = {};
  for (const file of ['app/components/note-editor.tsx', 'lib/note-content.ts']) {
    const target = path.join(directory, path.basename(file).replace(/\.tsx?$/, '.js'));
    fs.writeFileSync(target, ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX } }).outputText);
    alias['@/' + file.replace(/\.tsx?$/, '')] = target;
  }
  fs.writeFileSync(output, ts.transpileModule(fs.readFileSync(path.join(root, 'app/components/personal-notes.tsx'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX } }).outputText);
  fs.writeFileSync(path.join(directory, 'db.js'), `let rows=[];let seq=0;exports.supabase={from(){let op='select',payload,filters={};const chain={select(){return chain},eq(k,v){filters[k]=v;return chain},order(){return chain},insert(v){op='insert';payload=v;return chain},update(v){op='update';payload=v;return chain},delete(){op='delete';return chain},single(){return run(true)},then(a,b){return run(false).then(a,b)}};async function run(single){await new Promise(r=>setTimeout(r,100));if(window.failSave&&op==='update')return {data:null,error:{message:'offline'}};let data;if(op==='insert'){data={...payload,id:String(++seq),updated_at:new Date().toISOString()};rows.unshift(data);}else{const matches=rows.filter(row=>Object.entries(filters).every(([k,v])=>row[k]===v));if(op==='update')matches.forEach(row=>Object.assign(row,payload));if(op==='delete')rows=rows.filter(row=>!matches.includes(row));data=single?matches[0]:matches;}return {data:JSON.parse(JSON.stringify(data)),error:null}}return chain}};`);
  fs.appendFileSync(path.join(directory, 'db.js'), `window.linkTask=id=>{rows.find(row=>row.id===id).task_id='42';};`);
  fs.appendFileSync(path.join(directory, 'db.js'), `window.addListNote=()=>rows.push({id:'list-note',user_id:'user',title:'Lista de compras',content:'Para a reunião:\\n- Conferir estoque\\n2. Enviar pedido',updated_at:new Date().toISOString(),task_id:null});`);
  fs.writeFileSync(path.join(directory, 'entry.js'), `const React=require('react');const {createRoot}=require('react-dom/client');const {PersonalNotes}=require('./notes');const root=createRoot(document.getElementById('root'));window.renderNotes=(key='test')=>root.render(React.createElement(PersonalNotes,{key,userId:'user',onCreateTask:(noteId,title,content,subtasks)=>{window.taskDraft={noteId,title,content,subtasks}},onViewTask:async id=>{window.viewedTask=id}}));window.renderNotes();`);
  await new Promise((resolve, reject) => webpack({ mode: 'development', entry: path.join(directory, 'entry.js'), output: { path: directory, filename: 'bundle.js' }, resolve: { alias: { ...alias, '@/lib/supabase': path.join(directory, 'db.js') }, modules: [path.join(root, 'node_modules')] }, devtool: false }, (error, stats) => error || stats.hasErrors() ? reject(error || new Error(stats.toString())) : resolve()));
  const cssPath = path.join(root, 'app/globals.css');
  const css = await postcss([tailwind({ base: root })]).process(fs.readFileSync(cssPath, 'utf8'), { from: cssPath });
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.route('http://notes.test/**', route => route.fulfill({ contentType: 'text/html', body: '<html><body><div id="root"></div></body></html>' }));
    await page.goto('http://notes.test');
    await page.addStyleTag({ content: css.css });
    await page.addScriptTag({ path: path.join(directory, 'bundle.js') });
    const create = page.getByRole('button', { name: 'Nova nota' });
    await create.waitFor();
    await create.click();
    const title = page.getByLabel('Título da nota');
    const content = page.getByLabel('Conteúdo da nota');
    await title.fill('Reunião com fornecedores');
    await content.fill('Conferir prazos e valores.');
    await content.press('Control+a');
    await page.getByRole('button', { name: 'Negrito', exact: true }).click();
    assert.equal(await content.locator('strong').innerText(), 'Conferir prazos e valores.');
    await page.getByLabel('Tamanho da fonte', { exact: true }).selectOption('18px');
    assert.match(await content.innerHTML(), /font-size: 18px/);
    await page.getByRole('button', { name: 'Salvar', exact: true }).click();
    await page.getByText('Salvo na sua conta', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Criar tarefa', exact: true }).click();
    const taskDraft = await page.evaluate(() => window.taskDraft);
    assert.equal(taskDraft.title, 'Reunião com fornecedores');
    assert.equal(taskDraft.content, 'Conferir prazos e valores.');
    assert.ok(!taskDraft.content.includes('wally-rich-note'));
    await page.evaluate(() => { window.linkTask(window.taskDraft.noteId); window.renderNotes('linked'); });
    await page.getByRole('button', { name: 'Ver tarefa', exact: true }).click();
    await page.waitForFunction(() => window.viewedTask === '42');
    await page.evaluate(() => window.renderNotes('formatted'));
    await content.locator('strong').waitFor();
    assert.match(await content.innerHTML(), /font-size: 18px/);
    await content.click();
    await content.press('Control+a');
    await page.getByRole('button', { name: 'Itálico', exact: true }).click();
    await content.locator('em').waitFor();
    await page.getByRole('button', { name: 'Sublinhado', exact: true }).click();
    await content.locator('u').waitFor();
    await page.getByRole('button', { name: 'Marca-texto', exact: true }).click();
    await content.locator('mark').waitFor();
    await page.getByRole('button', { name: 'Centralizar', exact: true }).click();
    assert.match(await content.innerHTML(), /text-align: center/);
    await page.getByRole('button', { name: 'Lista com marcadores', exact: true }).click();
    await content.locator('ul').waitFor();
    await page.getByRole('button', { name: 'Lista numerada', exact: true }).click();
    await content.locator('ol').waitFor();
    await page.waitForTimeout(600);
    await page.getByRole('button', { name: 'Lista de tarefas', exact: true }).click();
    await content.locator('ul[data-type="taskList"]').waitFor();
    await page.getByRole('button', { name: 'Desfazer', exact: true }).click();
    await content.locator('ol').waitFor();
    await page.getByRole('button', { name: 'Refazer', exact: true }).click();
    await content.locator('ul[data-type="taskList"]').waitFor();
    page.removeAllListeners('dialog');
    page.on('dialog', dialog => dialog.accept(dialog.type() === 'prompt' ? 'https://example.com' : undefined));
    await page.getByRole('button', { name: 'Inserir ou remover link', exact: true }).click();
    await content.locator('a[href="https://example.com"]').waitFor();
    page.removeAllListeners('dialog');
    page.on('dialog', dialog => dialog.accept(dialog.type() === 'prompt' ? 'javascript:alert(1)' : undefined));
    await page.getByRole('button', { name: 'Inserir ou remover link', exact: true }).click();
    assert.equal(await content.locator('a[href^="javascript:"]').count(), 0);
    page.removeAllListeners('dialog');
    page.on('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Limpar formatação', exact: true }).click();
    await content.fill('Rascunho preservado ao trocar de aba.');
    await page.evaluate(() => window.renderNotes('remounted'));
    await page.waitForFunction(() => document.querySelector('[contenteditable="true"]')?.textContent === 'Rascunho preservado ao trocar de aba.');
    await page.evaluate(() => { window.failSave = true; });
    await page.getByRole('button', { name: 'Salvar', exact: true }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await content.innerText(), 'Rascunho preservado ao trocar de aba.');
    await page.evaluate(() => { window.failSave = false; });
    await page.getByRole('button', { name: 'Salvar', exact: true }).click();
    await page.getByText('Salvo na sua conta', { exact: true }).waitFor();
    await page.getByLabel('Buscar notas').fill('não existe');
    await page.getByText('Nenhuma nota encontrada.').waitFor();
    await page.getByLabel('Buscar notas').fill('');
    await page.screenshot({ path: path.join(directory, 'desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.getByRole('button', { name: 'Excluir nota', exact: true }).click();
    await page.getByText('Crie sua primeira nota', { exact: true }).waitFor();
    await page.evaluate(() => { window.addListNote(); window.renderNotes('list-conversion'); });
    await page.getByLabel('Título da nota').waitFor();
    await page.getByRole('button', { name: 'Criar tarefa', exact: true }).click();
    const listDraft = await page.evaluate(() => window.taskDraft);
    assert.equal(listDraft.content, 'Para a reunião:');
    assert.deepEqual(listDraft.subtasks, [{ title: 'Conferir estoque', done: false }, { title: 'Enviar pedido', done: false }]);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, screenshots: directory }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
