const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const postcss = require('postcss');
const tailwind = require('@tailwindcss/postcss');
const XLSX = require('xlsx-js-style');
const webpackModule = require('next/dist/compiled/webpack/webpack');
const webpack = webpackModule.webpack || webpackModule.default;
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');

(async () => {
  const root = path.resolve(__dirname, '..');
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'weekly-calendar-qa-'));
  const alias = {};
  for (const file of ['app/components/weekly-task-schedule-view.tsx', 'lib/task-priority.ts', 'lib/task-recurrence.ts']) {
    const output = path.join(directory, path.basename(file).replace(/\.tsx?$/, '.js'));
    fs.writeFileSync(output, ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX } }).outputText);
    alias['@/' + file.replace(/\.tsx?$/, '')] = output;
  }
  const task = (id, title, assigned_to, changes = {}) => ({ id, title, assigned_to, created_at: '2026-10-01T12:00:00-03:00', repeat_days: 'seg,ter,qua,qui,sex', repeat_interval: 1, lastOcc: '2026-10-28', nextOcc: '29/10/2026', last_done_date: null, category: 'Geral', workflow_status: 'pendente', priority: 'normal', ...changes });
  const tasks = [task('1', 'Conferir condições comerciais e prazos dos fornecedores', 'a', { workflow_status: 'em_andamento' }), task('2', 'Revisar os pedidos da semana', 'a', { last_done_date: '2026-10-27', priority: 'alta' }), task('3', 'Acompanhar entregas', 'b', { priority: 'baixa' }), task('4', 'Alinhamento da campanha de novembro', 'a', { repeat_days: '', is_one_off: true, due_date: '2026-11-03' })];
  fs.writeFileSync(path.join(directory, 'entry.js'), `const React=require('react');const {createRoot}=require('react-dom/client');const {WeeklyTaskScheduleView}=require('./weekly-task-schedule-view');const root=createRoot(document.getElementById('root'));window.renderWeekly=(selectedUserIds=[])=>root.render(React.createElement(WeeklyTaskScheduleView,{tasks:${JSON.stringify(tasks)},profiles:[{id:'a',full_name:'Wally Teste'},{id:'b',full_name:'Ana Teste'}],selectedUserIds,onView:task=>{window.openedTask=task.id}}));window.renderWeekly();`);
  await new Promise((resolve, reject) => webpack({ mode: 'development', entry: path.join(directory, 'entry.js'), output: { path: directory, filename: 'bundle.js' }, resolve: { alias, modules: [path.join(root, 'node_modules')] }, devtool: false }, (error, stats) => error || stats.hasErrors() ? reject(error || new Error(stats.toString())) : resolve()));
  const cssPath = path.join(root, 'app/globals.css');
  const css = await postcss([tailwind({ base: root })]).process(fs.readFileSync(cssPath, 'utf8'), { from: cssPath });
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.clock.install({ time: new Date('2026-10-28T12:00:00-03:00') });
    await page.setContent('<html><body><div style="padding:20px" id="root"></div></body></html>');
    await page.addStyleTag({ content: css.css }); await page.addScriptTag({ path: path.join(directory, 'bundle.js') });
    const calendar = page.getByRole('region', { name: 'Calendário de tarefas da semana', exact: true });
    await calendar.waitFor();
    assert.ok((await calendar.boundingBox()).width > 1500);
    const wednesday = page.getByRole('region', { name: 'Quarta 28/10/2026', exact: true });
    assert.equal(await wednesday.getByText('Em andamento', { exact: true }).count(), 1);
    const tuesday = page.getByRole('region', { name: 'Terça 27/10/2026', exact: true });
    assert.equal(await tuesday.getByText('Em andamento', { exact: true }).count(), 0);
    await wednesday.getByRole('button', { name: /Conferir condições/ }).click();
    assert.equal(await page.evaluate(() => window.openedTask), '1');
    await page.screenshot({ path: path.join(directory, 'desktop.png') });
    await page.getByRole('button', { name: 'Próxima semana', exact: true }).click();
    await page.getByText('02/11/2026 a 06/11/2026', { exact: false }).waitFor();
    await page.getByRole('button', { name: /Alinhamento da campanha/ }).waitFor();
    const weekMarker = page.getByRole('button', { name: 'Voltar para a semana atual', exact: true });
    assert.equal(await weekMarker.innerText(), 'Próxima semana');
    await page.getByRole('button', { name: 'Próxima semana', exact: true }).click();
    assert.equal(await weekMarker.innerText(), 'Daqui a 2 semanas');
    await weekMarker.click();
    assert.equal(await weekMarker.innerText(), 'Esta semana');
    await page.getByRole('button', { name: 'Semana anterior', exact: true }).click();
    assert.equal(await weekMarker.innerText(), 'Semana anterior');
    await page.getByRole('button', { name: 'Semana anterior', exact: true }).click();
    assert.equal(await weekMarker.innerText(), 'Há 2 semanas');
    await weekMarker.click();
    await page.evaluate(() => window.renderWeekly(['a']));
    await page.getByRole('button', { name: /Acompanhar entregas/ }).first().waitFor({ state: 'detached' });
    assert.equal(await page.getByRole('button', { name: /Acompanhar entregas/ }).count(), 0);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exportar XLSX', exact: true }).click();
    const download = await downloadPromise;
    const exportPath = path.join(directory, 'schedule.xlsx');
    await download.saveAs(exportPath);
    const workbook = XLSX.readFile(exportPath);
    assert.equal(workbook.SheetNames.length, 1);
    const sheet = workbook.Sheets[workbook.SheetNames[0]];
    assert.equal(sheet.A1.v, 'Segunda');
    assert.equal(sheet.B1.v, 'Terça');
    assert.ok(JSON.stringify(sheet).includes('Revisar os pedidos'));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, screenshots: directory }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
